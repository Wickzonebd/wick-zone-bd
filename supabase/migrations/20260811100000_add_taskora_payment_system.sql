alter table public.invoices enable row level security;
alter table public.payment_audit_logs enable row level security;

create policy "payment settings readable"
on public.payment_settings for select
to authenticated
using (true);

create policy "payment settings admin update"
on public.payment_settings for update
to authenticated
using ((select public.is_payment_admin()))
with check ((select public.is_payment_admin()));

create policy "users read own payments"
on public.payments for select
to authenticated
using (user_id = (select auth.uid()) or (select public.is_payment_admin()));

create policy "users read own invoices"
on public.invoices for select
to authenticated
using (user_id = (select auth.uid()) or (select public.is_payment_admin()));

create policy "admins read payment audit"
on public.payment_audit_logs for select
to authenticated
using ((select public.is_payment_admin()));

-- Intentionally no INSERT/UPDATE/DELETE policies for normal authenticated users.
-- Server-side payment functions use the service role and are the only writers.

