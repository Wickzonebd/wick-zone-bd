-- Taskora professional payment system foundation.
-- Provider API calls remain server-side; this migration owns durable state,
-- access control, idempotency and verified-payment activation.

create extension if not exists pgcrypto;

create table if not exists public.payment_settings (
  id boolean primary key default true check (id),
  payment_enabled boolean not null default false,
  provider_name text,
  currency text not null default 'BDT',
  merchant_name text not null default 'Taskora',
  merchant_logo text,
  support_phone text,
  support_email text,
  payment_success_message text not null default 'আপনার পেমেন্ট সফলভাবে সম্পন্ন হয়েছে।',
  payment_failed_message text not null default 'পেমেন্ট সম্পন্ন করা যায়নি। আবার চেষ্টা করুন।',
  invoice_footer text,
  terms_text text,
  micro_job_activation_price numeric(12,2),
  verification_price numeric(12,2),
  verification_enabled boolean not null default true,
  verification_duration_days integer,
  updated_at timestamptz not null default now()
);

insert into public.payment_settings (id)
values (true)
on conflict (id) do nothing;

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  invoice_id text not null unique,
  transaction_id text unique,
  provider_transaction_id text unique,
  amount numeric(12,2) not null check (amount >= 0),
  currency text not null default 'BDT',
  payment_method text,
  status text not null default 'pending' check (status in ('pending','processing','paid','failed','cancelled','refunded')),
  payment_type text not null check (payment_type in ('micro_jobs','verification','reselling','other')),
  item_id text,
  item_name text not null,
  customer_name text,
  customer_email text,
  customer_phone text,
  provider_response jsonb,
  provider_checkout_url text,
  provider_session_id text unique,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  cancelled_at timestamptz,
  failed_at timestamptz,
  updated_at timestamptz not null default now()
);

create index if not exists payments_user_created_idx on public.payments(user_id, created_at desc);
create index if not exists payments_status_created_idx on public.payments(status, created_at desc);
create index if not exists payments_type_created_idx on public.payments(payment_type, created_at desc);

create table if not exists public.invoices (
  id uuid primary key default gen_random_uuid(),
  invoice_number text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  payment_id uuid not null unique references public.payments(id) on delete cascade,
  customer_name text,
  customer_email text,
  customer_phone text,
  item_name text not null,
  item_description text,
  subtotal numeric(12,2) not null default 0,
  discount numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  currency text not null default 'BDT',
  status text not null default 'pending' check (status in ('pending','paid','failed','cancelled','refunded')),
  transaction_id text,
  payment_method text,
  issued_at timestamptz not null default now(),
  paid_at timestamptz
);

create index if not exists invoices_user_issued_idx on public.invoices(user_id, issued_at desc);

create table if not exists public.payment_audit_logs (
  id bigint generated by default as identity primary key,
  payment_id uuid references public.payments(id) on delete cascade,
  invoice_id text,
  event text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists payment_audit_payment_idx on public.payment_audit_logs(payment_id, created_at desc);

create sequence if not exists public.taskora_invoice_sequence start 1;

create or replace function public.next_taskora_invoice_number()
returns text
language sql
security invoker
set search_path = public
as $$
  select 'TASK-' || to_char(current_date, 'YYYY') || '-' || lpad(nextval('public.taskora_invoice_sequence')::text, 6, '0');
$$;

revoke all on function public.next_taskora_invoice_number() from public, anon, authenticated;
grant execute on function public.next_taskora_invoice_number() to service_role;

create or replace function public.is_payment_admin()
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = (select auth.uid()) and role = 'admin'
  );
$$;

grant execute on function public.is_payment_admin() to authenticated;

alter table public.payment_settings enable row level security;
