grant select on public.payments to authenticated;
grant select on public.invoices to authenticated;
grant select on public.payment_audit_logs to authenticated;

create or replace function public.get_payment_checkout_config(p_type text)
returns jsonb
language plpgsql
stable
security invoker
set search_path = public
as $$
declare
  s public.payment_settings%rowtype;
  price numeric(12,2);
begin
  select * into s from public.payment_settings where id = true;
  if not found then return jsonb_build_object('enabled', false); end if;

  if p_type = 'micro_jobs' then
    price := s.micro_job_activation_price;
  elsif p_type = 'verification' then
    if not s.verification_enabled then
      return jsonb_build_object('enabled', false, 'reason', 'verification_disabled');
    end if;
    price := s.verification_price;
  else
    price := null;
  end if;

  return jsonb_build_object(
    'enabled', s.payment_enabled,
    'providerName', s.provider_name,
    'currency', s.currency,
    'merchantName', s.merchant_name,
    'merchantLogo', s.merchant_logo,
    'supportPhone', s.support_phone,
    'supportEmail', s.support_email,
    'termsText', s.terms_text,
    'price', price
  );
end;
$$;

grant execute on function public.get_payment_checkout_config(text) to authenticated;

-- Called ONLY by trusted server code after the provider verification API confirms
-- invoice, amount and final paid status. Service-role access is required.
create or replace function public.finalize_verified_payment(
  p_payment_id uuid,
  p_transaction_id text,
  p_provider_transaction_id text,
  p_payment_method text,
  p_provider_response jsonb default '{}'::jsonb
)
returns public.payments
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  pay public.payments%rowtype;
  inv public.invoices%rowtype;
  order_id uuid;
begin
  select * into pay from public.payments where id = p_payment_id for update;
  if not found then raise exception 'payment_not_found'; end if;

  if pay.status = 'paid' then return pay; end if;
  if pay.status in ('cancelled','refunded') then raise exception 'payment_not_payable'; end if;

  if exists (select 1 from public.payments where transaction_id = p_transaction_id and id <> pay.id) then
    raise exception 'duplicate_transaction';
  end if;

  update public.payments
  set status = 'paid',
      transaction_id = p_transaction_id,
      provider_transaction_id = coalesce(p_provider_transaction_id, provider_transaction_id),
      payment_method = p_payment_method,
      provider_response = coalesce(p_provider_response, '{}'::jsonb),
      paid_at = coalesce(paid_at, now()),
      updated_at = now()
  where id = pay.id
  returning * into pay;

  update public.invoices
  set status = 'paid', transaction_id = pay.transaction_id,
      payment_method = pay.payment_method, paid_at = pay.paid_at
  where payment_id = pay.id
  returning * into inv;

  if pay.payment_type = 'micro_jobs' then
    insert into public.memberships (user_id, status, activated_at, activation_source)
    values (pay.user_id, 'active', pay.paid_at, 'payment')
    on conflict (user_id) do update
      set status = 'active', activated_at = excluded.activated_at, activation_source = 'payment';
  elsif pay.payment_type = 'verification' then
    update public.profiles set is_social_verified = true where id = pay.user_id;
  elsif pay.payment_type = 'reselling' and pay.item_id is not null then
    begin
      order_id := pay.item_id::uuid;
      update public.reselling_orders
      set status = case when status = 'cancelled' then status else 'processing' end
      where id = order_id and user_id = pay.user_id;
    exception when invalid_text_representation then
      null;
    end;
  end if;

  insert into public.payment_audit_logs(payment_id, invoice_id, event, details)
  values (pay.id, pay.invoice_id, 'payment_verified', jsonb_build_object('transaction_id', pay.transaction_id));

  -- Notification delivery is non-critical. A notification schema change must not
  -- roll back an otherwise verified payment or its purchased entitlement.
  begin
    insert into public.notifications(user_id, title, body, category)
    values (
      pay.user_id,
      'Payment successful',
      case
        when pay.payment_type = 'micro_jobs' then 'আপনার পেমেন্ট সফলভাবে সম্পন্ন হয়েছে। Micro Jobs অ্যাক্সেস সক্রিয় করা হয়েছে।'
        when pay.payment_type = 'verification' then 'আপনার পেমেন্ট সফলভাবে সম্পন্ন হয়েছে। Verified Badge সক্রিয় করা হয়েছে।'
        else 'আপনার পেমেন্ট সফলভাবে সম্পন্ন হয়েছে।'
      end,
      'wallet'
    );
  exception when others then
    insert into public.payment_audit_logs(payment_id, invoice_id, event, details)
    values (pay.id, pay.invoice_id, 'notification_failed', jsonb_build_object('message', sqlerrm));
  end;

  return pay;
end;
$$;

revoke all on function public.finalize_verified_payment(uuid,text,text,text,jsonb) from public, anon, authenticated;
grant execute on function public.finalize_verified_payment(uuid,text,text,text,jsonb) to service_role;

create or replace function public.mark_payment_failed(
  p_payment_id uuid,
  p_event text,
  p_provider_response jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare pay public.payments%rowtype;
begin
  select * into pay from public.payments where id = p_payment_id for update;
  if not found or pay.status = 'paid' then return; end if;

  if p_event = 'cancelled' then
    update public.payments set status='cancelled', cancelled_at=now(), provider_response=p_provider_response, updated_at=now() where id=p_payment_id;
    update public.invoices set status='cancelled' where payment_id=p_payment_id;
  else
    update public.payments set status='failed', failed_at=now(), provider_response=p_provider_response, updated_at=now() where id=p_payment_id;
    update public.invoices set status='failed' where payment_id=p_payment_id;
  end if;

  insert into public.payment_audit_logs(payment_id, invoice_id, event, details)
  values (p_payment_id, pay.invoice_id, case when p_event='cancelled' then 'payment_cancelled' else 'payment_failed' end, p_provider_response);
end;
$$;

revoke all on function public.mark_payment_failed(uuid,text,jsonb) from public, anon, authenticated;
grant execute on function public.mark_payment_failed(uuid,text,jsonb) to service_role;
